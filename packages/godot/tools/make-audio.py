#!/usr/bin/env python3
"""Synthesizes the world's ambience loops and footsteps (M7b) into packages/godot/assets/audio/*.wav.

Nothing here is recorded or downloaded: every sound is made from noise and sines with numpy (a fixed seed, so running the
script again gives the same files). Run it only to change the sounds:

    python3 packages/godot/tools/make-audio.py          # writes assets/audio/*.wav (then: godot --headless --import)

Loops are seamless by construction: noise is filtered in the frequency domain (which makes it periodic over the loop),
the envelopes are periodic, and one-shot events (a chirp, a croak, a pop) are added with wrap-around. Footsteps are three
short variants for each ground. Licence: these files are generated by this script and are CC0 (see assets/LICENSES.md).
"""
import os
import wave

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "assets", "audio")
LOOP_RATE = 16000  # ambience: 16 kHz is plenty (the hiss and the chirps are under 8 kHz) and keeps the files small
STEP_RATE = 22050
rng = np.random.default_rng(1234)


def write(name, x, rate, peak=0.8):
    x = np.asarray(x, dtype=np.float64)
    m = float(np.max(np.abs(x))) or 1.0
    x = x / m * peak
    pcm = (np.clip(x, -1, 1) * 32767).astype("<i2")
    os.makedirs(OUT, exist_ok=True)
    with wave.open(os.path.join(OUT, name + ".wav"), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(rate)
        w.writeframes(pcm.tobytes())
    print("%-18s %5.1f s  %4d KB" % (name, len(x) / rate, pcm.nbytes // 1024))


def band(n, rate, lo, hi, slope=0.0):
    """White noise through a smooth band-pass in the frequency domain (periodic over n samples)."""
    spec = rng.standard_normal(n // 2 + 1) + 1j * rng.standard_normal(n // 2 + 1)
    f = np.fft.rfftfreq(n, 1.0 / rate)
    g = np.clip((f - lo) / max(1.0, lo * 0.4), 0, 1) * np.clip((hi - f) / max(1.0, hi * 0.3), 0, 1)
    if slope:
        g = g * (np.maximum(f, 20.0) / 1000.0) ** slope
    return np.fft.irfft(spec * g, n)


def slow(n, rate, cutoff, depth=1.0):
    """A slowly wandering envelope in 0..1 (periodic): low-passed noise."""
    x = band(n, rate, 0.02, cutoff)
    x = x / (np.max(np.abs(x)) or 1.0)
    return 0.5 + 0.5 * depth * x


def add(buf, at, ev):
    """Adds an event at sample `at`, wrapping round the end of the loop."""
    n = len(buf)
    idx = (at + np.arange(len(ev))) % n
    np.add.at(buf, idx, ev)


def chirp(rate, f0, f1, dur, harm=0.25):
    t = np.arange(int(dur * rate)) / rate
    f = f0 + (f1 - f0) * (t / dur) ** 1.3
    ph = 2 * np.pi * np.cumsum(f) / rate
    env = np.sin(np.pi * np.clip(t / dur, 0, 1)) ** 1.5
    return (np.sin(ph) + harm * np.sin(2 * ph)) * env


def loop_wind(name, secs, lo, hi, gust, whistle):
    n = int(secs * LOOP_RATE)
    x = band(n, LOOP_RATE, lo, hi, slope=-0.6)
    env = slow(n, LOOP_RATE, 0.5, gust)
    x = x * (0.25 + 0.75 * env**1.5)
    if whistle:
        t = np.arange(n) / LOOP_RATE
        w = band(n, LOOP_RATE, whistle * 0.9, whistle * 1.1) * 6.0
        x = x + w * env**3 * 0.5
    write(name, x, LOOP_RATE, 0.7)


def loop_rain(name, secs, muffled):
    n = int(secs * LOOP_RATE)
    if muffled:  # on the roof from inside: low hiss, soft patter and the odd drip
        x = band(n, LOOP_RATE, 120, 1300, slope=-0.3) * 0.8
        drops = np.zeros(n)
        for _ in range(int(secs * 38)):
            d = np.exp(-np.arange(int(0.02 * LOOP_RATE)) / (0.004 * LOOP_RATE)) * rng.standard_normal(int(0.02 * LOOP_RATE))
            add(drops, int(rng.integers(0, n)), d * rng.uniform(0.2, 1.0))
        spec = np.fft.rfft(drops)
        f = np.fft.rfftfreq(n, 1.0 / LOOP_RATE)
        drops = np.fft.irfft(spec * (f < 1400), n)
        x = x + drops * 0.9
        for _ in range(int(secs * 0.7)):  # a drip from the eave
            t = np.arange(int(0.12 * LOOP_RATE)) / LOOP_RATE
            tick = np.sin(2 * np.pi * rng.uniform(380, 620) * t) * np.exp(-t / 0.025)
            add(x, int(rng.integers(0, n)), tick * 0.7)
    else:
        x = band(n, LOOP_RATE, 1500, 7800) * 0.8 + band(n, LOOP_RATE, 300, 1500) * 0.35
        x = x * (0.8 + 0.2 * slow(n, LOOP_RATE, 3.0))
        for _ in range(int(secs * 90)):  # single drops on leaves
            d = np.exp(-np.arange(int(0.012 * LOOP_RATE)) / (0.002 * LOOP_RATE)) * rng.standard_normal(int(0.012 * LOOP_RATE))
            add(x, int(rng.integers(0, n)), d * rng.uniform(0.2, 0.9) * 1.2)
    write(name, x, LOOP_RATE, 0.7)


def loop_birds(name, secs):
    n = int(secs * LOOP_RATE)
    x = np.zeros(n)
    x += band(n, LOOP_RATE, 150, 700, slope=-0.5) * 0.02  # a breath of air under them
    species = [
        lambda: [chirp(LOOP_RATE, 3600, 4700, 0.07)] * rng.integers(3, 6),  # "tsee tsee tsee"
        lambda: [chirp(LOOP_RATE, 2300, 3400, 0.11), chirp(LOOP_RATE, 3400, 2500, 0.1)],  # a two-note call
        lambda: [chirp(LOOP_RATE, 2800 + 140 * k, 2900 + 140 * k, 0.05, 0.1) for k in range(8)],  # a rising trill
        lambda: [chirp(LOOP_RATE, 5000, 3000, 0.16, 0.4)],  # a falling whistle
    ]
    at = 0.4
    while at < secs - 1.0:
        notes = species[int(rng.integers(0, len(species)))]()
        pos = at
        vol = rng.uniform(0.35, 1.0)
        for nt in notes:
            add(x, int(pos * LOOP_RATE), nt * vol)
            pos += len(nt) / LOOP_RATE + rng.uniform(0.03, 0.07)
        at = pos + rng.uniform(0.6, 2.2)
    write(name, x, LOOP_RATE, 0.7)


def loop_crickets(name, secs):
    n = int(secs * LOOP_RATE)
    t = np.arange(n) / LOOP_RATE
    x = np.zeros(n)
    for k in range(5):
        f = 4300 + 180 * k + rng.uniform(-40, 40)
        chirps_per_s = 2 + k  # integer per second so the loop is seamless
        pulses = 3 + (k % 2)
        ph = (t * chirps_per_s) % 1.0
        gate = np.zeros(n)
        for p in range(pulses):
            c = 0.1 + p * 0.07
            gate += np.exp(-((ph - c) / 0.014) ** 2)
        carrier = np.sin(2 * np.pi * np.round(f * secs) / secs * t + rng.uniform(0, 6))
        x += carrier * gate * (0.6 + 0.4 * np.sin(2 * np.pi * (1 + k) / secs * t + k) ** 2) * 0.35
    write(name, x, LOOP_RATE, 0.6)


def loop_frogs(name, secs):
    n = int(secs * LOOP_RATE)
    x = band(n, LOOP_RATE, 90, 500, slope=-0.5) * 0.03
    for _ in range(int(secs * 0.9)):
        f = rng.uniform(140, 260)
        base = int(rng.uniform(0, secs) * LOOP_RATE)
        for k in range(int(rng.integers(1, 4))):
            dur = 0.16
            t = np.arange(int(dur * LOOP_RATE)) / LOOP_RATE
            body = np.sin(2 * np.pi * f * t * (1.0 + 0.1 * t / dur)) + 0.5 * np.sin(4 * np.pi * f * t)
            body *= 0.6 + 0.4 * np.sin(2 * np.pi * 70 * t)
            body *= np.sin(np.pi * t / dur) ** 1.2
            add(x, base + int(k * 0.22 * LOOP_RATE), body * rng.uniform(0.5, 1.0))
    write(name, x, LOOP_RATE, 0.6)


def loop_water(name, secs):
    n = int(secs * LOOP_RATE)
    hiss = band(n, LOOP_RATE, 350, 4800, slope=0.3)
    bub = np.abs(band(n, LOOP_RATE, 5, 40)) ** 1.0
    bub = bub / (np.max(bub) or 1.0)
    x = hiss * (0.35 + 0.65 * bub)
    for _ in range(int(secs * 14)):  # gurgles: short upward sweeps
        dur = rng.uniform(0.03, 0.08)
        t = np.arange(int(dur * LOOP_RATE)) / LOOP_RATE
        f = rng.uniform(500, 900) + rng.uniform(300, 800) * t / dur
        g = np.sin(2 * np.pi * np.cumsum(f) / LOOP_RATE) * np.sin(np.pi * t / dur)
        add(x, int(rng.integers(0, n)), g * rng.uniform(0.1, 0.35) * np.std(x) * 4)
    write(name, x, LOOP_RATE, 0.65)


def loop_surf(name, secs):
    n = int(secs * LOOP_RATE)
    t = np.arange(n) / LOOP_RATE
    x = band(n, LOOP_RATE, 120, 3200, slope=-0.2)
    period = secs / 2.0
    ph = (t % period) / period
    env = np.where(ph < 0.45, (ph / 0.45) ** 2, np.exp(-(ph - 0.45) * 5.5)) * 0.85 + 0.12
    fizz = band(n, LOOP_RATE, 2500, 7500) * np.where(ph > 0.4, np.exp(-(ph - 0.4) * 4.5), 0) * 0.4
    write(name, x * env + fizz * env, LOOP_RATE, 0.7)


def loop_fire(name, secs):
    n = int(secs * LOOP_RATE)
    x = band(n, LOOP_RATE, 50, 380, slope=-0.4) * 0.5 * (0.6 + 0.4 * slow(n, LOOP_RATE, 6.0))
    for _ in range(int(secs * 22)):
        dur = rng.uniform(0.004, 0.02)
        k = np.arange(int(dur * LOOP_RATE) + 2)
        pop = rng.standard_normal(len(k)) * np.exp(-k / (dur * LOOP_RATE * 0.35))
        add(x, int(rng.integers(0, n)), pop * rng.uniform(0.2, 1.4) * rng.choice([0.5, 1.0, 1.0, 2.0]))
    write(name, x, LOOP_RATE, 0.7)


def loop_murmur(name, secs):
    """The village's murmur: a few voices that never say anything: buzzing at 110–230 Hz through vowel formants, in syllables."""
    n = int(secs * LOOP_RATE)
    t = np.arange(n) / LOOP_RATE
    out = np.zeros(n)
    for v in range(6):
        f0 = rng.uniform(110, 230)
        vib = 1 + 0.02 * np.sin(2 * np.pi * int(rng.integers(40, 70)) * t / secs)
        ph = 2 * np.pi * np.cumsum(np.round(f0 * secs) / secs * vib) / LOOP_RATE
        src = sum(np.sin(h * ph) / h for h in range(1, 14))
        spec = np.fft.rfft(src)
        f = np.fft.rfftfreq(n, 1.0 / LOOP_RATE)
        f1, f2 = rng.uniform(350, 800), rng.uniform(1100, 2300)
        g = np.exp(-((f - f1) / 160) ** 2) + 0.6 * np.exp(-((f - f2) / 300) ** 2)
        voice = np.fft.irfft(spec * g, n)
        syl = np.zeros(n)
        pos = rng.uniform(0, 1.0)
        while pos < secs:
            dur = rng.uniform(0.12, 0.28)
            tt = np.arange(int(dur * LOOP_RATE)) / LOOP_RATE
            add(syl, int(pos * LOOP_RATE), np.sin(np.pi * tt / dur) ** 2)
            pos += dur + (rng.uniform(0.02, 0.1) if rng.random() < 0.8 else rng.uniform(0.6, 1.8))
        out += voice * np.minimum(syl, 1.0) * (0.5 + 0.5 * slow(n, LOOP_RATE, 0.4))
    out += band(n, LOOP_RATE, 150, 1200) * 0.1
    write(name, out, LOOP_RATE, 0.6)


def owl(name, hoots):
    rate = LOOP_RATE
    out = np.zeros(int(2.4 * rate))
    pos = 0.1
    for i, d in enumerate(hoots):
        t = np.arange(int(d * rate)) / rate
        f = 410 - 40 * t / d
        ph = 2 * np.pi * np.cumsum(f) / rate
        env = np.sin(np.pi * np.clip(t / d, 0, 1)) ** 0.8
        h = (np.sin(ph) + 0.35 * np.sin(2 * ph) + 0.1 * np.sin(3 * ph)) * env * (0.8 + 0.2 * np.sin(2 * np.pi * 5 * t))
        out[int(pos * rate): int(pos * rate) + len(h)] += h
        pos += d + 0.18
    write(name, out, rate, 0.6)


# --- footsteps -------------------------------------------------------------------------------------------------------
def burst(dur, lo, hi, attack, decay, rate=STEP_RATE):
    n = int(dur * rate)
    x = band(n * 4, rate, lo, hi)[:n]
    t = np.arange(n) / rate
    return x * np.minimum(t / attack, 1.0) * np.exp(-t / decay)


def thump(dur, f, decay, rate=STEP_RATE):
    t = np.arange(int(dur * rate)) / rate
    return np.sin(2 * np.pi * f * t * (1.0 - 0.3 * t / dur)) * np.exp(-t / decay)


def put(x, at, ev, gain=1.0):
    m = min(len(ev), len(x) - at)
    if m > 0:
        x[at: at + m] += ev[:m] * gain


def step_sound(kind, v):
    n = int(0.3 * STEP_RATE)
    x = np.zeros(n)
    j = 1.0 + 0.12 * (v - 1)  # each variant a little different in pitch and weight
    if kind == "grass":
        b = burst(0.14, 400, 3800 * j, 0.025, 0.05)
        put(x, 0, b, 1.0)
        put(x, 0, thump(0.07, 90 * j, 0.025), 0.5)
    elif kind == "dirt":
        b = burst(0.11, 150, 1700 * j, 0.006, 0.03)
        put(x, 0, b, 1.1)
        put(x, 0, thump(0.08, 75 * j, 0.03), 0.8)
    elif kind == "stone":
        b = burst(0.05, 1200, 5200, 0.001, 0.008)
        put(x, 0, b, 0.9)
        t = np.arange(int(0.12 * STEP_RATE)) / STEP_RATE
        put(x, 0, np.sin(2 * np.pi * 820 * j * t) * np.exp(-t / 0.012), 0.6)
        put(x, 0, thump(0.05, 110, 0.015), 0.5)
    elif kind == "wood":
        put(x, 0, thump(0.13, 190 * j, 0.03), 1.0)
        t = np.arange(int(0.1 * STEP_RATE)) / STEP_RATE
        put(x, 0, np.sin(2 * np.pi * 470 * j * t) * np.exp(-t / 0.014), 0.45)
        b = burst(0.03, 800, 4000, 0.001, 0.006)
        put(x, 0, b, 0.7)
    elif kind == "sand":
        b = burst(0.16, 700, 4200, 0.03, 0.06)
        put(x, 0, b, 0.6)
        for _ in range(14):
            put(x, int(rng.integers(0, 3300)), rng.standard_normal(40) * np.exp(-np.arange(40) / 8), 0.25)
    elif kind == "snow":
        b = burst(0.2, 1800, 7500, 0.02, 0.08)
        put(x, 0, b, 0.5)
        for _ in range(26):
            put(x, int(rng.integers(0, 4200)), rng.standard_normal(30) * np.exp(-np.arange(30) / 5), 0.4)
    elif kind == "water":
        b = burst(0.22, 350, 3200, 0.03, 0.09)
        put(x, 0, b, 0.8)
        for k in range(4):
            dur = 0.05
            t = np.arange(int(dur * STEP_RATE)) / STEP_RATE
            g = np.sin(2 * np.pi * np.cumsum(500 + (600 + 300 * k) * t / dur) / STEP_RATE) * np.sin(np.pi * t / dur)
            at = int((0.03 + 0.045 * k + rng.uniform(0, 0.02)) * STEP_RATE)
            put(x, at, g, 0.35)
    write("step_%s_%d" % (kind, v), x, STEP_RATE, 0.75)


def main():
    loop_wind("wind_soft", 10, 90, 900, 0.8, 520)
    loop_wind("wind_hard", 10, 110, 2600, 1.0, 780)
    loop_rain("rain", 8, False)
    loop_rain("rain_roof", 8, True)
    loop_birds("birds", 16)
    loop_crickets("crickets", 8)
    loop_frogs("frogs", 12)
    loop_water("water", 8)
    loop_surf("surf", 14)
    loop_fire("fire", 8)
    loop_murmur("murmur", 12)
    owl("owl_1", [0.42, 0.55])
    owl("owl_2", [0.3, 0.3, 0.7])
    for kind in ["grass", "dirt", "stone", "wood", "sand", "snow", "water"]:
        for v in range(3):
            step_sound(kind, v)


if __name__ == "__main__":
    main()
